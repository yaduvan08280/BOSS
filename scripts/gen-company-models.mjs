#!/usr/bin/env node
// Writes packages/db/src/company-models.ts: the models whose rows belong to one company (a required
// `companyId`). The database client's company wall is built from it; a test fails when it is out of date.
//   node scripts/gen-company-models.mjs
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const dir = fileURLToPath(new URL('../prisma/schema/', import.meta.url));
export function companyModels() {
  const names = [];
  for (const file of readdirSync(dir)
    .filter((f) => f.endsWith('.prisma'))
    .sort()) {
    const text = readFileSync(dir + file, 'utf8');
    for (const m of text.matchAll(/^model (\w+) \{([\s\S]*?)^\}/gm))
      if (/^\s+companyId\s+String\s/m.test(m[2])) names.push(m[1]);
  }
  return names.sort();
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const names = companyModels();
  const body = `// Generated by scripts/gen-company-models.mjs from prisma/schema — do not edit by hand.
/** Models whose every row belongs to one company (a required \`companyId\`). */
export const COMPANY_MODELS: ReadonlySet<string> = new Set([
${names.map((n) => `  '${n}',`).join('\n')}
]);
`;
  writeFileSync(fileURLToPath(new URL('../packages/db/src/company-models.ts', import.meta.url)), body);
  console.log(`${names.length} models`);
}
