import { execFileSync } from 'node:child_process';
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { describe, expect, it } from 'vitest';
import { COMPANY_MODELS } from './company-models';

describe('the company wall', () => {
  it('knows every model with a required companyId (run `node scripts/gen-company-models.mjs` after a schema change)', () => {
    const root = join(import.meta.dirname, '../../..');
    const now = execFileSync(
      process.execPath,
      [
        '--input-type=module',
        '-e',
        "import { companyModels } from './scripts/gen-company-models.mjs'; console.log(JSON.stringify(companyModels()))",
      ],
      { cwd: root, encoding: 'utf8' },
    );
    expect([...COMPANY_MODELS].sort()).toEqual(JSON.parse(now));
    expect(readFileSync(join(root, 'packages/db/src/company-models.ts'), 'utf8')).toContain('Generated by');
  });
});
