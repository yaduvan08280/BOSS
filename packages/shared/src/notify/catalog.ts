export type NotifyEvent = {
  event: string;
  module: string;
  audience: Audience;
  to: string[];
  title: { en: string; hi: string };
  body: { en: string; hi: string };
};

export const NOTIFY_EVENTS: NotifyEvent[] = ROWS.map(
  ([event, audience, to, titleEn, bodyEn, titleHi, bodyHi]) => ({
    event,
    module: event.split('.')[0]!,
    audience,
    to,
    title: { en: titleEn, hi: titleHi },
    body: { en: bodyEn, hi: bodyHi },
  }),
);

export const NOTIFY_EVENT_NAMES = NOTIFY_EVENTS.map((e) => e.event);
export const NOTIFY_MODULES = [...new Set(NOTIFY_EVENTS.map((e) => e.module))];

